package utils

import (
	"bytes"
	"details-subscription-service/models"
	"fmt"
	"time"

	"github.com/go-pdf/fpdf"
)

func GenerateReportPDF(areaName string, periodStart, periodEnd time.Time, reports []models.AreaReport) ([]byte, error) {
	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.SetAutoPageBreak(true, 15)
	pdf.AddPage()

	// Title
	pdf.SetFont("Arial", "B", 18)
	pdf.CellFormat(190, 12, "CleanApp Detail Report", "", 1, "C", false, 0, "")
	pdf.Ln(4)

	// Area and date range
	pdf.SetFont("Arial", "", 12)
	pdf.CellFormat(190, 8, fmt.Sprintf("Area: %s", areaName), "", 1, "C", false, 0, "")
	pdf.CellFormat(190, 8, fmt.Sprintf("Period: %s - %s",
		periodStart.Format("Jan 2, 2006 15:04 MST"),
		periodEnd.Format("Jan 2, 2006 15:04 MST")), "", 1, "C", false, 0, "")
	pdf.Ln(6)

	// Summary
	pdf.SetFont("Arial", "B", 14)
	pdf.CellFormat(190, 10, "Summary", "", 1, "L", false, 0, "")

	severityCounts := map[string]int{"Low": 0, "Medium": 0, "High": 0, "Critical": 0}
	classificationCounts := map[string]int{}
	for _, r := range reports {
		switch {
		case r.SeverityLevel < 0.25:
			severityCounts["Low"]++
		case r.SeverityLevel < 0.5:
			severityCounts["Medium"]++
		case r.SeverityLevel < 0.75:
			severityCounts["High"]++
		default:
			severityCounts["Critical"]++
		}
		if r.Classification != "" {
			classificationCounts[r.Classification]++
		}
	}

	pdf.SetFont("Arial", "", 11)
	pdf.CellFormat(190, 7, fmt.Sprintf("Total reports: %d", len(reports)), "", 1, "L", false, 0, "")
	pdf.CellFormat(190, 7, fmt.Sprintf("By severity - Critical: %d, High: %d, Medium: %d, Low: %d",
		severityCounts["Critical"], severityCounts["High"], severityCounts["Medium"], severityCounts["Low"]), "", 1, "L", false, 0, "")
	for classification, count := range classificationCounts {
		pdf.CellFormat(190, 7, fmt.Sprintf("Classification '%s': %d reports", classification, count), "", 1, "L", false, 0, "")
	}
	pdf.Ln(6)

	if len(reports) == 0 {
		pdf.SetFont("Arial", "I", 11)
		pdf.CellFormat(190, 10, "No new reports in this period.", "", 1, "C", false, 0, "")
	} else {
		// Report table header
		pdf.SetFont("Arial", "B", 9)
		pdf.SetFillColor(220, 220, 220)
		pdf.CellFormat(55, 8, "Title", "1", 0, "L", true, 0, "")
		pdf.CellFormat(50, 8, "Summary", "1", 0, "L", true, 0, "")
		pdf.CellFormat(18, 8, "Severity", "1", 0, "C", true, 0, "")
		pdf.CellFormat(35, 8, "Location", "1", 0, "C", true, 0, "")
		pdf.CellFormat(32, 8, "Time", "1", 1, "C", true, 0, "")

		// Report rows
		pdf.SetFont("Arial", "", 8)
		for _, r := range reports {
			title := truncate(r.Title, 30)
			summary := truncate(r.Summary, 28)
			location := fmt.Sprintf("%.4f, %.4f", r.Latitude, r.Longitude)
			ts := r.Timestamp.Format("Jan 2 15:04")
			severity := formatSeverity(r.SeverityLevel)

			pdf.CellFormat(55, 7, title, "1", 0, "L", false, 0, "")
			pdf.CellFormat(50, 7, summary, "1", 0, "L", false, 0, "")
			pdf.CellFormat(18, 7, severity, "1", 0, "C", false, 0, "")
			pdf.CellFormat(35, 7, location, "1", 0, "C", false, 0, "")
			pdf.CellFormat(32, 7, ts, "1", 1, "C", false, 0, "")
		}
	}

	// Footer
	pdf.Ln(10)
	pdf.SetFont("Arial", "I", 8)
	pdf.CellFormat(190, 6, fmt.Sprintf("Generated by CleanApp Details Subscription Service on %s", time.Now().Format("Jan 2, 2006 15:04 MST")), "", 1, "C", false, 0, "")

	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, fmt.Errorf("failed to generate PDF: %w", err)
	}
	return buf.Bytes(), nil
}

func truncate(s string, maxLen int) string {
	if len(s) <= maxLen {
		return s
	}
	return s[:maxLen-3] + "..."
}

func formatSeverity(level float64) string {
	switch {
	case level < 0.25:
		return "Low"
	case level < 0.5:
		return "Medium"
	case level < 0.75:
		return "High"
	default:
		return "Critical"
	}
}
