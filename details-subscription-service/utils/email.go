package utils

import (
	"encoding/base64"
	"fmt"
	"log"
	"time"

	"github.com/sendgrid/sendgrid-go"
	"github.com/sendgrid/sendgrid-go/helpers/mail"
)

type EmailSender struct {
	client    *sendgrid.Client
	fromName  string
	fromEmail string
}

func NewEmailSender(apiKey, fromName, fromEmail string) *EmailSender {
	return &EmailSender{
		client:    sendgrid.NewSendClient(apiKey),
		fromName:  fromName,
		fromEmail: fromEmail,
	}
}

func (e *EmailSender) SendReportPDF(recipientEmail, areaName string, periodStart, periodEnd time.Time, pdfBytes []byte) error {
	from := mail.NewEmail(e.fromName, e.fromEmail)
	to := mail.NewEmail("", recipientEmail)

	dateRange := fmt.Sprintf("%s - %s", periodStart.Format("Jan 2, 2006 15:04"), periodEnd.Format("Jan 2, 2006 15:04"))
	subject := fmt.Sprintf("CleanApp Detail Report: %s - %s", areaName, periodEnd.Format("Jan 2, 2006"))

	plainText := fmt.Sprintf("Your CleanApp Detail Report for %s (%s) is attached.", areaName, dateRange)
	htmlContent := fmt.Sprintf(`<p>Your CleanApp Detail Report for <strong>%s</strong> is attached.</p>
<p>Period: %s</p>
<p>Please review the attached PDF for full details.</p>
<p style="color: #888; font-size: 12px;">This report was generated by CleanApp Details Subscription Service.</p>`, areaName, dateRange)

	message := mail.NewSingleEmail(from, subject, to, plainText, htmlContent)

	attachment := mail.NewAttachment()
	attachment.SetContent(base64.StdEncoding.EncodeToString(pdfBytes))
	attachment.SetType("application/pdf")
	attachment.SetFilename(fmt.Sprintf("detail-report-%s.pdf", periodEnd.Format("2006-01-02-1504")))
	attachment.SetDisposition("attachment")
	message.AddAttachment(attachment)

	response, err := e.client.Send(message)
	if err != nil {
		log.Printf("Failed to send email to %s: %v", recipientEmail, err)
		return fmt.Errorf("failed to send email: %w", err)
	}

	if response.StatusCode < 200 || response.StatusCode >= 300 {
		log.Printf("SendGrid returned status %d for email to %s: %s", response.StatusCode, recipientEmail, response.Body)
		return fmt.Errorf("email send failed with status %d", response.StatusCode)
	}

	log.Printf("Report email sent to %s (status %d)", recipientEmail, response.StatusCode)
	return nil
}
